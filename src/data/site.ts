export const cleanCaption = (c: string) =>
  c
    .replace(/[\u2068\u2069]/g, '')
    .replace(/\\+\s*$/g, '')
    .replace(/\t/g, ' ')
    .trim();

export const captionBody = (c: string) =>
  cleanCaption(c)
    .replace(/#[^\s#]+/g, '')
    .replace(/\n{3,}/g, '\n\n')
    .trim();

export const hashtags = (c: string) => cleanCaption(c).match(/#[^\s#]+/g) ?? [];

export const firstLine = (c: string) => captionBody(c).split('\n').find((l) => l.trim().length > 0)?.trim() ?? '';

